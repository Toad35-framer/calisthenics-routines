/* Cadre du dessin : englobe les deux images, ratio 200:140, sol en bas. */
function fitBox(pose) {
  let x0 = 1e9, y0 = 1e9, x1 = -1e9, y1 = -1e9;
  pose.forEach(function (fr) {
    [fr.n, fr.f, fr.t].forEach(function (g) {
      g.forEach(function (l) {
        for (let k = 0; k < l.length; k += 2) {
          x0 = Math.min(x0, l[k]); x1 = Math.max(x1, l[k]);
          y0 = Math.min(y0, l[k + 1]); y1 = Math.max(y1, l[k + 1]);
        }
      });
    });
    x0 = Math.min(x0, fr.h[0] - 9); x1 = Math.max(x1, fr.h[0] + 9);
    y0 = Math.min(y0, fr.h[1] - 9); y1 = Math.max(y1, fr.h[1] + 9);
  });
  y1 = Math.max(y1, 132); x0 -= 12; x1 += 12; y0 -= 8;
  let w = x1 - x0, h = y1 - y0;
  const r = 200 / 140;
  if (w / h < r) { const nw = h * r; x0 -= (nw - w) / 2; w = nw; }
  else { const nh = w / r; y0 -= (nh - h); h = nh; }
  return { x: x0, y: y0, w: w, h: h };
}
